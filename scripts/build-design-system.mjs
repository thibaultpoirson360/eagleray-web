// Builds design-system/styles.css from the site's Tailwind theme.
//
// The Tailwind @theme block in src/styles/global.css is the single source of
// truth for colours, fonts, spacing, radii, easing and fluid type. This script
// copies those variables into a plain-CSS :root block so the design system can
// be used without Tailwind, then appends design-system/base.css (the heading
// rules and the Google Fonts import). Run `npm run design-system` after
// changing a token in global.css; the site itself is not affected.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const globalCss = readFileSync(join(root, "src/styles/global.css"), "utf8");
const base = readFileSync(join(root, "design-system/base.css"), "utf8");

// Only the @theme block, and only its top-level custom properties. Keyframes
// live inside the block too, but they are not variables, so they are skipped.
const themeMatch = globalCss.match(/@theme\s*\{([\s\S]*?)\n\}/);
if (!themeMatch) throw new Error("No @theme block found in src/styles/global.css");

const lines = themeMatch[1]
  .split("\n")
  .map((line) => line.replace(/\/\*[\s\S]*?\*\//g, "").trim())
  .filter((line) => line.startsWith("--") && line.includes(":"));

const variables = lines.map((line) => `  ${line.replace(/;\s*$/, "")};`);

// Keyframes sit inside the @theme block, so the animation variables above need
// them copied out as real @keyframes rules. Braces are counted, so nested
// frames are kept whole.
const keyframes = [];
const body = themeMatch[1];
for (let start = body.indexOf("@keyframes"); start !== -1; start = body.indexOf("@keyframes", start + 1)) {
  let depth = 0;
  let end = start;
  for (; end < body.length; end++) {
    if (body[end] === "{") depth++;
    if (body[end] === "}" && --depth === 0) break;
  }
  keyframes.push(body.slice(start, end + 1).replace(/^\s+/gm, (indent) => indent.replace(/ {4}/g, "  ")));
}

const output = [
  "/* Generated by scripts/build-design-system.mjs from src/styles/global.css.",
  "   Do not edit by hand: change the token in global.css, then run `npm run design-system`. */",
  "",
  ":root {",
  ...variables,
  "  --rail: 0px;",
  "}",
  "",
  ...keyframes,
  "",
  "@media (min-width: 64rem) {",
  "  :root {",
  "    --rail: 84px;",
  "  }",
  "}",
  "",
  base.trimEnd(),
  "",
].join("\n");

writeFileSync(join(root, "design-system/styles.css"), output);
console.log(`design-system/styles.css: ${variables.length} variables, ${keyframes.length} keyframe sets`);
